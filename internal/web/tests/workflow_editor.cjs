const { before, after, test } = require('node:test');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const baseURL = process.env.HARNESS_TEST_URL || 'http://127.0.0.1:7777';
let browser;
before(async () => { browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] }); });
after(async () => { await browser?.close(); });
async function openEditor(t, viewport = {width:1280,height:900}) {
  const page = await browser.newPage({viewport});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  t.after(async () => { await page.close(); assert.deepEqual(errors, []); });
  await page.addInitScript(() => { window.EventSource = class {}; });
  await page.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.origin !== new URL(baseURL).origin) return route.abort();
    if (url.pathname === '/api/status') return route.fulfill({json:{tasks:[],events:[],repositories:[],stats:{},resources:{}}});
    if (url.pathname === '/api/agent-auth') return route.fulfill({json:{ok:true,auth:{required:false,ready:true,state:'ready'}}});
    if (url.pathname === '/api/review-settings') return route.fulfill({json:{ok:true,settings:{workflow_enabled:true}}});
    if (url.pathname.startsWith('/api/')) return route.fulfill({json:{ok:true}});
    return route.continue();
  });
  await page.goto(`${baseURL}/#workflow`);
  await page.locator('.wf-node').first().waitFor();
  return page;
}
test('workflow editing, moving, connecting, validation, and saved drafts', async t => {
  const page = await openEditor(t);
  assert.equal(await page.locator('.wf-node').count(),5);
  await page.getByRole('button',{name:'Validate',exact:true}).click();
  assert.match(await page.locator('.wf-notice').innerText(),/structure looks good/);
  await page.getByRole('button',{name:'Dismiss message'}).click();
  const agent=page.locator('.react-flow__node[data-id="agent"]');
  await agent.click();
  await page.getByLabel('Step name',{exact:true}).fill('Implement the feature');
  await page.getByLabel('Step configuration').fill('Implement and test the requested change.');
  const before=await agent.boundingBox();
  await page.mouse.move(before.x+30,before.y+30); await page.mouse.down();
  await page.mouse.move(before.x+90,before.y+50,{steps:10}); await page.mouse.up();
  const moved=await agent.boundingBox(); assert.ok(moved.x > before.x+30);
  const edge=page.locator('.react-flow__edge[data-id="approval-action"]');
  await edge.focus(); await page.keyboard.press('Enter'); await page.keyboard.press('Delete');
  await page.waitForFunction(()=>document.querySelectorAll('.react-flow__edge').length===4);
  const a=await page.locator('.react-flow__node[data-id="approval"] .react-flow__handle.source').boundingBox();
  const b=await page.locator('.react-flow__node[data-id="action"] .react-flow__handle.target').boundingBox();
  await page.mouse.move(a.x+a.width/2,a.y+a.height/2); await page.mouse.down();
  await page.mouse.move(b.x+b.width/2,b.y+b.height/2,{steps:15}); await page.mouse.up();
  await page.waitForFunction(()=>document.querySelectorAll('.react-flow__edge').length===5);
  await page.locator('.wf-step').filter({hasText:'Agent'}).click();
  assert.equal(await page.locator('.wf-node').count(),6);
  await page.getByRole('button',{name:'Validate',exact:true}).click();
  assert.match(await page.locator('.wf-notice').innerText(),/disconnected/);
  await page.getByRole('button',{name:'Delete step',exact:true}).click();
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('agent00.workflow.draft.v1')));
  assert.equal(stored.nodes.length,5); assert.equal(stored.edges.length,5);
  assert.equal(stored.nodes.find(n=>n.id==='agent').data.label,'Implement the feature');
  await page.reload(); await page.locator('.wf-node').first().waitFor();
  assert.equal(await agent.locator('strong').innerText(),'Implement the feature');
  assert.match(await page.locator('.wf-save-state').innerText(),/Saved locally/);
  const editor=await page.locator('.wf-editor').boundingBox(),dock=await page.locator('.page-bottom-dock').boundingBox();
  assert.ok(editor.y+editor.height <= dock.y,'editor stays above navigation');
  await page.locator('#prompt-mode-builder').click();
  assert.equal(await page.locator('.wf-editor').isVisible(),false);
});
test('workflow editor fits mobile and opens a usable inspector', async t => {
  const page=await openEditor(t,{width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
  await page.locator('.react-flow__node[data-id="agent"]').click();
  assert.equal(await page.getByLabel('Step configuration').isVisible(),true);
  await page.getByRole('button',{name:'Close step settings'}).click();
  assert.equal(await page.locator('.wf-inspector').isVisible(),false);
});
